import {mkdtemp,mkdir,cp,readFile,access,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../../',import.meta.url));
const fixture=await mkdtemp(path.join(tmpdir(),'transcol-publication-'));
await mkdir(path.join(fixture,'scripts'));
await cp(path.join(root,'scripts/prepare-site.mjs'),path.join(fixture,'scripts/prepare-site.mjs'));
await cp(path.join(root,'estoque'),path.join(fixture,'estoque'),{recursive:true});
await mkdir(path.join(fixture,'.secrets'));await writeFile(path.join(fixture,'.secrets/private.txt'),'TEST ONLY');
const run=key=>spawnSync(process.execPath,[path.join(fixture,'scripts/prepare-site.mjs')],{encoding:'utf8',env:{...process.env,SUPABASE_URL:'https://test.supabase.co',SUPABASE_PUBLISHABLE_KEY:key}});
assert.notEqual(run('sb_secret_test_only').status,0);
const result=run('sb_publishable_test_only');assert.equal(result.status,0,result.stderr);
for(const forbidden of ['supabase','tests','scripts','.secrets','.descarte'])await assert.rejects(access(path.join(fixture,'dist',forbidden)));
assert.match(await readFile(path.join(fixture,'dist/assets/js/config.js'),'utf8'),/sb_publishable_test_only/);
assert.match(await readFile(path.join(fixture,'dist/index.html'),'utf8'),/connect-src https:\/\/test.supabase.co;/);
assert.equal(await readFile(path.join(fixture,'estoque/assets/js/config.js'),'utf8'),await readFile(path.join(root,'estoque/assets/js/config.js'),'utf8'));
assert.notEqual(run('sb_publishable_test_only').status,0);
console.log('Publicação: artefato público isolado, CSP restrita, chave secreta recusada, fonte preservada e saída existente protegida: OK.');
